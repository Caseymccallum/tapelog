package policy

// Text rendering and comment-preserving insertion for Policy Studio
// candidates. Nothing here writes to disk: it returns bytes for an operator
// to review, simulate and save explicitly.

import (
	"bytes"
	"errors"
	"fmt"
	"strings"

	"gopkg.in/yaml.v3"
)

// yamlRule is the on-disk shape of one generated rule. The field set is
// exactly what normalize() compiles.
type yamlRule struct {
	ID      string   `yaml:"id"`
	Tool    []string `yaml:"tool"`
	Action  string   `yaml:"action"`
	Reason  string   `yaml:"reason"`
	Where   []string `yaml:"where,omitempty"`
	Tasks   []string `yaml:"tasks,omitempty"`
	Expires string   `yaml:"expires,omitempty"`
}

// ruleBlock renders a validated draft as a YAML sequence item. indent is the
// whitespace before "- "; nl is the line ending to use.
func ruleBlock(d RuleDraft, indent, nl string) (string, error) {
	var where []string
	for _, c := range d.Conditions {
		expr, err := ConditionExpr(c)
		if err != nil {
			return "", err
		}
		where = append(where, expr)
	}
	r := yamlRule{ID: d.ID, Tool: d.Tools, Action: d.Action, Reason: d.Reason, Where: where, Tasks: d.Tasks, Expires: d.Expires}
	var buf bytes.Buffer
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(&r); err != nil {
		return "", fmt.Errorf("render rule: %w", err)
	}
	if err := enc.Close(); err != nil {
		return "", fmt.Errorf("render rule: %w", err)
	}
	lines := strings.Split(strings.TrimRight(buf.String(), "\n"), "\n")
	var b strings.Builder
	for i, line := range lines {
		if i == 0 {
			b.WriteString(indent + "- " + line + nl)
			continue
		}
		b.WriteString(indent + "  " + line + nl)
	}
	return b.String(), nil
}

// RuleYAML renders a validated draft as it appears under `rules:` at the
// conventional two-space indent.
func RuleYAML(d RuleDraft) (string, error) {
	return ruleBlock(d, "  ", "\n")
}

const candidateHeader = `# Tapelog policy candidate — generated by the Session Workbench Policy Studio.
#
# This is a proposal, not an active configuration. Tapelog never activates a
# candidate for you: review it, simulate it, then save it yourself.
#
# Simulate it against a recording with:
#   tapelog policy whatif --policy <this file> <recording.jsonl>
# Try sample calls with:
#   tapelog policy test --policy <this file> --calls calls.jsonl

`

// NewCandidate renders a standalone candidate document containing exactly the
// rule the operator asked for, plus an explicit default.
func NewCandidate(defaultAction string, d RuleDraft) ([]byte, error) {
	return NewCandidateWithLimits(defaultAction, d, LimitsDraft{})
}

// NewCandidateWithLimits is NewCandidate plus an optional limit block.
func NewCandidateWithLimits(defaultAction string, d RuleDraft, lim LimitsDraft) ([]byte, error) {
	if !validAction(defaultAction) {
		return nil, fmt.Errorf("default must be allow, deny or confirm (got %q)", defaultAction)
	}
	if err := lim.Validate(); err != nil {
		return nil, err
	}
	block, err := RuleYAML(d)
	if err != nil {
		return nil, err
	}
	var b strings.Builder
	b.WriteString(candidateHeader)
	b.WriteString("version: 1\n")
	b.WriteString("default: " + defaultAction + "\n")
	b.WriteString("rules:\n")
	b.WriteString(block)
	if lim.Set() {
		b.WriteString("\nlimits:\n")
		if lim.MaxCalls > 0 {
			fmt.Fprintf(&b, "  max_calls: %d\n", lim.MaxCalls)
		}
		if lim.MaxPerMinute > 0 {
			fmt.Fprintf(&b, "  max_per_minute: %d\n", lim.MaxPerMinute)
		}
		if lim.MaxResponseBytes > 0 {
			fmt.Fprintf(&b, "  max_response_bytes: %d\n", lim.MaxResponseBytes)
		}
	}
	return []byte(b.String()), nil
}

// LimitsDraft is the optional session-limit block of a new candidate.
// Zero means "not set". These are the limits internal/limits actually
// enforces; the Studio does not invent others.
type LimitsDraft struct {
	MaxCalls         int `json:"max_calls"`
	MaxPerMinute     int `json:"max_per_minute"`
	MaxResponseBytes int `json:"max_response_bytes"`
}

// Set reports whether any limit was requested.
func (l LimitsDraft) Set() bool {
	return l.MaxCalls > 0 || l.MaxPerMinute > 0 || l.MaxResponseBytes > 0
}

// Validate rejects values the boundary would refuse to compile.
func (l LimitsDraft) Validate() error {
	if l.MaxCalls < 0 || l.MaxPerMinute < 0 || l.MaxResponseBytes < 0 {
		return errors.New("limits cannot be negative")
	}
	if l.MaxCalls > 1000000 {
		return errors.New("max_calls must be 1,000,000 or fewer")
	}
	if l.MaxPerMinute > 100000 {
		return errors.New("max_per_minute must be 100,000 or fewer")
	}
	if l.MaxResponseBytes > 1<<30 {
		return errors.New("max_response_bytes must be 1 GiB or fewer")
	}
	return nil
}

// UniqueID turns base into an id that does not collide with taken.
func UniqueID(base string, taken map[string]bool) string {
	if base == "" {
		base = "rule"
	}
	if !taken[base] {
		return base
	}
	for i := 2; i < 1000; i++ {
		candidate := fmt.Sprintf("%s-%d", base, i)
		if !taken[candidate] {
			return candidate
		}
	}
	return base + "-candidate"
}

// InsertRule places a validated rule at the top of the existing `rules:`
// block and changes nothing else. Every original byte outside the insertion
// point is preserved, so comments, unknown fields and hand-written `where`
// expressions survive. It refuses shapes it cannot edit safely.
func InsertRule(source []byte, d RuleDraft) ([]byte, error) {
	s := string(source)
	if strings.TrimSpace(s) == "" {
		return nil, errors.New("there is no policy source to extend")
	}
	nl := "\n"
	if strings.Contains(s, "\r\n") {
		nl = "\r\n"
	}

	// Locate a top-level `rules:` key.
	lineStart := 0
	found := false
	for lineStart <= len(s) {
		nlAt := strings.IndexByte(s[lineStart:], '\n')
		lineEnd := len(s)
		if nlAt >= 0 {
			lineEnd = lineStart + nlAt
		}
		bare := strings.TrimSuffix(s[lineStart:lineEnd], "\r")
		if strings.HasPrefix(bare, "rules:") {
			rest := strings.TrimSpace(strings.TrimPrefix(bare, "rules:"))
			switch {
			case rest == "" || strings.HasPrefix(rest, "#"):
				found = true
			case rest == "[]":
				block, err := ruleBlock(d, "  ", nl)
				if err != nil {
					return nil, err
				}
				head := s[:lineStart] + "rules:" + nl + block
				if nlAt >= 0 {
					return []byte(head + s[lineEnd+1:]), nil
				}
				return []byte(head), nil
			default:
				return nil, fmt.Errorf("this policy writes its rules inline (%q); add the rule with a text editor or start a new candidate file", short(rest))
			}
			break
		}
		if nlAt < 0 {
			break
		}
		lineStart = lineEnd + 1
	}

	if found {
		headEnd := len(s)
		if i := strings.IndexByte(s[lineStart:], '\n'); i >= 0 {
			headEnd = lineStart + i + 1
		}
		indent := "  "
		// Reuse the indentation of the first existing rule item, if any.
		for scan := headEnd; scan < len(s); {
			nlAt := strings.IndexByte(s[scan:], '\n')
			lineEnd := len(s)
			if nlAt >= 0 {
				lineEnd = scan + nlAt
			}
			bare := strings.TrimSuffix(s[scan:lineEnd], "\r")
			trimmed := strings.TrimLeft(bare, " \t")
			if trimmed != "" && !strings.HasPrefix(trimmed, "#") {
				if strings.HasPrefix(trimmed, "- ") || trimmed == "-" {
					indent = bare[:len(bare)-len(trimmed)]
				}
				break
			}
			if nlAt < 0 {
				break
			}
			scan = lineEnd + 1
		}
		block, err := ruleBlock(d, indent, nl)
		if err != nil {
			return nil, err
		}
		var b strings.Builder
		b.WriteString(s[:headEnd])
		if !strings.HasSuffix(s[:headEnd], "\n") {
			b.WriteString(nl)
		}
		b.WriteString(block)
		b.WriteString(s[headEnd:])
		return []byte(b.String()), nil
	}

	// No rules key: append a new section. Key order is not significant in
	// YAML, so this cannot change how the existing document is read.
	block, err := ruleBlock(d, "  ", nl)
	if err != nil {
		return nil, err
	}
	var b strings.Builder
	b.WriteString(s)
	if !strings.HasSuffix(s, "\n") {
		b.WriteString(nl)
	}
	b.WriteString(nl + "rules:" + nl)
	b.WriteString(block)
	return []byte(b.String()), nil
}

